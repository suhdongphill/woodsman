/**
 * GCRM v2 — 지표 정의 (명세 §2-3).
 *
 * ## ⚠ 새 수집 파이프라인이 아니다
 * 모든 지표는 포털이 **이미 매일 받고 있는 계열**(`lib/macro/registry.ts` · D1 `MacroPoint`)을 가리킨다.
 * `series`가 그 키다. 같은 지표가 사이트 안에서 두 값을 갖는 사고를 막는 유일한 방법이다(명세 §C-1).
 *
 * ## ⚠ `portalTransform`과 `transform`은 다른 것이다 — 겹쳐 쓰면 두 번 변환된다
 * `MacroPoint`에는 **원값**이 들어 있다. 화면은 레지스트리의 `transform`(yoy 등)을 읽을 때 적용한다.
 * - `portalTransform` — 레지스트리가 쓰는 변환. **대조용으로 적어 둔 사실**이다(테스트가 레지스트리와 맞춰 본다).
 * - `transform` — 그 위에 GCRM이 **더** 거는 변환. 기본은 `level`(더 걸지 않는다).
 *   여기에 `yoy`를 또 적으면 전년비의 전년비가 된다.
 *
 * ## 점수 축 (단계 0 원칙 2)
 * `polarity: +1`은 **값이 높을수록 자본에 우호**, `-1`은 불리다. 정규화의 마지막에 `-1`이면
 * `100 − score`로 뒤집고, **뒤집은 뒤에는 raw와 섞지 않는다.**
 * ⚠ 한 지표가 기둥마다 뜻이 달라지는 경우(달러인덱스)는 여기서 뒤집지 않고
 *   `pillars.ts`의 `polarity` 덮어쓰기로 **이유와 함께** 처리한다.
 *
 * ## ⚠ `freq`는 선언이 아니라 실측이다 (조사 §2-1)
 * 레지스트리가 `d`라고 적어도 2024년 관측이 12점이면 그 계열은 월간이다. 선언을 믿고 5일 창을
 * 잡으면 **조용히 5개월 창**이 된다. 실측이 다른 계열에는 주석으로 근거를 남겼다.
 *
 * ## 이력 길이를 함께 적는 이유 (조사 §2-2)
 * `minObs`를 통과해도 3년짜리의 「99번째 백분위」는 3년 중 최악일 뿐이다.
 * 화면이 그 구분을 말할 수 있도록 `historyStart`·`points`를 정의에 남긴다(2026-09-19 실측).
 */
