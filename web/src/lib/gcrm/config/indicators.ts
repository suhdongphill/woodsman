export const GCRM_INDICATOR_BY_CODE = new Map(GCRM_INDICATORS.map((i) => [i.code, i]));

/** 실제로 계산에 들어가는 지표. */
export function enabledIndicators(): GcrmIndicator[] {
  return GCRM_INDICATORS.filter((i) => i.enabled);
}

/**
 * 이 지표가 참여하는 축 (§2-4).
 * - 분기·월간 지표는 **조류에만** — 억지로 주간화하지 않는다
 * - 주간 지표는 조류·바람에만
 * ⚠ 나머지 축에서는 0점이 아니라 `MISSING`이다(분모에서 빠진다).
 */
export function axesFor(freq: Freq): ("tide" | "wind" | "wave")[] {
  if (freq === "q" || freq === "m") return ["tide"];
  if (freq === "w") return ["tide", "wind"];
  return ["tide", "wind", "wave"];
}
