/** 명세 §2-10 — 승격·확인에 쓰는 독립 채널 6개. 정의는 `channels.ts`. */
export type ChannelCode = "PRICE" | "CREDIT" | "FUNDING" | "RATES" | "FX" | "COMMODITY";

/** 공표 주기. 저빈도 지표가 어느 축에 참여하는지를 이 값이 정한다(§2-4). */
export type Freq = "d" | "w" | "m" | "q";

export type GcrmIndicator = {
  /** GCRM 안에서의 코드. 지금은 포털 키와 같게 둔다 — 다르면 대조가 안 된다. */
  code: string;
  nameKo: string;
  /** ⚠ 포털 `MacroIndicator.key`. 이것이 D1 `MacroPoint.seriesKey`다. */
  series: string;
  source: string;
  seriesId?: string;
  /** ⚠ 실측 주기(선언이 아니다). */
  freq: Freq;
  /** 레지스트리가 쓰는 변환 — 대조용 사실. 테스트가 맞춰 본다. */
  portalTransform: string;
  /** GCRM이 **더** 거는 변환. 기본 `level`. */
  transform: "level" | "yoy" | "mom" | "diff" | "ratio";
  /** +1 우호 · −1 불리 */
  polarity: 1 | -1;
  scaler: "pct_rank" | "zscore_cdf";
  window: "expanding" | "rolling";
  /** 미달이면 예외가 아니라 `MISSING`이다. */
  minObs: number;
  maxWindow: number;
  winsor: [number, number];
  channels: ChannelCode[];
  evidence: EvidenceKind;
  /** 2026-09-19 운영 D1 실측. 없으면 미수집. */
  historyStart: string | null;
  points: number;
  /** 파생 계열처럼 `points`가 0인 이유. ⚠ 「이력이 없다」와 「저장하지 않는다」는 다른 것이다. */
  historyNote?: string;
  enabled: boolean;
  /** `enabled: false`인 이유. ⚠ 끈 지표에는 반드시 적는다(검증기가 강제한다). */
  disabledReason?: string;
  glossary?: string;
};

