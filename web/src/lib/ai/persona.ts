/**
 * AI 페르소나 — 화면 기능마다 다른 역할과 말투를 고정한다.
 *
 * ## 왜 화면마다 다른가
 * 같은 모델에 같은 프롬프트를 던지면 어느 화면에서든 똑같은 "종합 분석"이 나온다.
 * 기업분석 화면은 **편입 논리를 쓰는 운용자**가 필요하고, 차트 화면은
 * **추세만 건조하게 읽는 관찰자**가 필요하다. 역할이 다르면 좋은 출력의 모양도 다르다.
 *
 * ## Woodsman 철학은 협상 대상이 아니다
 * 이 사이트는 "추천하지 않는다"를 정체성으로 내걸었고 정책 문서에도 그렇게 썼다
 * (`/disclaimer`). AI 출력이 매수 권유처럼 읽히면 사이트 전체가 거짓말이 된다.
 * 그래서 공통 규범(`WOODSMAN_DOCTRINE`)을 모든 페르소나 앞에 붙이고,
 * 개별 페르소나가 그걸 덮어쓸 수 없게 한다.
 */

