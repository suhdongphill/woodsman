/** 최종 시스템 프롬프트 — 공통 규범이 항상 앞에 온다. */
export function buildSystemPrompt(task: AiTask): string {
  const p = PERSONAS[task];
  return `${WOODSMAN_DOCTRINE}

--- 이번 작업에서 당신의 역할 ---
${p.role}

--- 출력 형식 ---
${p.outputSpec}`;
}

export function listPersonas(): Persona[] {
  return Object.values(PERSONAS);
}
